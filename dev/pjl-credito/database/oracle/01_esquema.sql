CREATE TABLE tb_usuario (
  id_usuario            NUMBER(8)     GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT pk_usuario PRIMARY KEY,
  usuario               VARCHAR2(40)  NOT NULL CONSTRAINT uk_usuario UNIQUE,
  nombre_completo       VARCHAR2(120) NOT NULL,
  rol                   VARCHAR2(15)  NOT NULL CONSTRAINT ck_usuario_rol CHECK (rol IN ('SOCIO','ASESOR','ANALISTA','RIESGO','COMITE','OPERACIONES','CARTERA','COBRANZA','ADMIN')),
  agencia               VARCHAR2(60),
  correo                VARCHAR2(120),                -- personal: recibe el enlace para recuperar la clave
  id_socio              NUMBER(10)    CONSTRAINT fk_usuario_socio REFERENCES tb_socio,
  clave_hash            VARCHAR2(200) NOT NULL,
  activo                CHAR(1)       DEFAULT 'S' NOT NULL CONSTRAINT ck_usuario_activo CHECK (activo IN ('S','N')),
  ultimo_acceso         TIMESTAMP,
  CONSTRAINT ck_usuario_socio CHECK ((rol = 'SOCIO' AND id_socio IS NOT NULL) OR (rol <> 'SOCIO')),
  CONSTRAINT ck_usuario_correo CHECK (correo IS NULL OR correo LIKE '%_@_%._%')
);

-- Recuperación de clave: se guarda solo el SHA-256 del token; vence y se usa una sola vez
CREATE TABLE tb_recuperacion_clave (
  id_recuperacion       NUMBER(12)    GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT pk_recuperacion_clave PRIMARY KEY,
  id_usuario            NUMBER(8)     NOT NULL CONSTRAINT fk_recuperacion_usuario REFERENCES tb_usuario,
  hash_token            CHAR(64)      NOT NULL CONSTRAINT uk_recuperacion_token UNIQUE,
  expira                TIMESTAMP     NOT NULL,
  usado                 TIMESTAMP,
  ip_origen             VARCHAR2(45),
  fecha_solicitud       TIMESTAMP     DEFAULT LOCALTIMESTAMP NOT NULL
);
CREATE INDEX ix_recuperacion_usuario ON tb_recuperacion_clave (id_usuario, fecha_solicitud);

