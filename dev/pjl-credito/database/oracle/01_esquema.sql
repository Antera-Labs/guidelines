CREATE TABLE tb_solicitud_credito (
  id_solicitud          NUMBER(10)    GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT pk_solicitud PRIMARY KEY,
  id_socio              NUMBER(10)    NOT NULL CONSTRAINT fk_solicitud_socio REFERENCES tb_socio,
  id_producto           NUMBER(6)     NOT NULL CONSTRAINT fk_solicitud_producto REFERENCES tb_producto_credito,
  id_consentimiento     NUMBER(10)    CONSTRAINT fk_solicitud_consent REFERENCES tb_consentimiento_lopdp,
  tipo_credito          VARCHAR2(15)  NOT NULL CONSTRAINT ck_sol_tipo CHECK (tipo_credito IN ('CONSUMO','MICROCREDITO','VIVIENDA','COMERCIAL')),
  tipo_pago             VARCHAR2(10)  DEFAULT 'FIJO' NOT NULL CONSTRAINT ck_sol_pago CHECK (tipo_pago IN ('FIJO','VARIABLE')),
  calidad               VARCHAR2(10)  DEFAULT 'DEUDOR' NOT NULL CONSTRAINT ck_sol_calidad CHECK (calidad IN ('DEUDOR','GARANTE')),
  destino               VARCHAR2(250) NOT NULL,
  monto_solicitado      NUMBER(12,2)  NOT NULL CONSTRAINT ck_sol_monto CHECK (monto_solicitado > 0),
  plazo_meses           NUMBER(3)     NOT NULL CONSTRAINT ck_sol_plazo CHECK (plazo_meses BETWEEN 1 AND 240),
  canal                 VARCHAR2(10)  NOT NULL CONSTRAINT ck_sol_canal CHECK (canal IN ('AGENCIA','MOVIL','WEB')),
  agencia               VARCHAR2(60)  NOT NULL,
  id_asesor             NUMBER(8)     CONSTRAINT fk_solicitud_asesor REFERENCES tb_usuario,
  id_etapa              NUMBER(1)     DEFAULT 1 NOT NULL CONSTRAINT fk_solicitud_etapa REFERENCES tb_etapa,
  id_subetapa           VARCHAR2(4)   DEFAULT '1.1' NOT NULL CONSTRAINT fk_solicitud_subetapa REFERENCES tb_subetapa,
  estado                VARCHAR2(15)  DEFAULT 'EN_PROCESO' NOT NULL CONSTRAINT ck_sol_estado CHECK (estado IN ('EN_PROCESO','EN_COMITE','APROBADA','RECHAZADA','DESEMBOLSADA','ANULADA')),
  dictamen              VARCHAR2(20)  CONSTRAINT ck_sol_dictamen CHECK (dictamen IN ('APROBADO','RECHAZADO','SUJETO_VERIFICACION')),
  es_pep                CHAR(1)       DEFAULT 'N' NOT NULL CONSTRAINT ck_sol_pep CHECK (es_pep IN ('S','N')),
  declara_licitud       CHAR(1)       DEFAULT 'S' NOT NULL CONSTRAINT ck_sol_licitud CHECK (declara_licitud IN ('S','N')),
  croquis_casa_lat      NUMBER(9,6),
  croquis_casa_lng      NUMBER(9,6),
  croquis_negocio_lat   NUMBER(9,6),
  croquis_negocio_lng   NUMBER(9,6),
  observaciones         VARCHAR2(1000),
  fecha_solicitud       TIMESTAMP     DEFAULT LOCALTIMESTAMP NOT NULL,
  fecha_etapa           TIMESTAMP     DEFAULT LOCALTIMESTAMP NOT NULL,
  fecha_cierre          TIMESTAMP
);

