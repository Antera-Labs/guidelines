CREATE TABLE tb_etapa (
  id_etapa        NUMBER(1)        CONSTRAINT pk_etapa PRIMARY KEY,
  nombre          VARCHAR2(60)     NOT NULL,
  descripcion     VARCHAR2(300),
  caso_uso        VARCHAR2(10)     NOT NULL
);

CREATE TABLE tb_subetapa (
  id_subetapa     VARCHAR2(4)      CONSTRAINT pk_subetapa PRIMARY KEY,
  id_etapa        NUMBER(1)        NOT NULL CONSTRAINT fk_subetapa_etapa REFERENCES tb_etapa,
  nombre          VARCHAR2(80)     NOT NULL,
  capacidades     VARCHAR2(400),
  automatica      CHAR(1)          DEFAULT 'N' NOT NULL CONSTRAINT ck_subetapa_auto CHECK (automatica IN ('S','N')),
  orden           NUMBER(2)        NOT NULL
);

-- Tarifario: "Tasas de interés de productos de crédito" (transcrito de la hoja física)
CREATE TABLE tb_producto_credito (
  id_producto           NUMBER(6)     CONSTRAINT pk_producto PRIMARY KEY,
  codigo                VARCHAR2(6)   NOT NULL,
  segmento              VARCHAR2(20)  NOT NULL CONSTRAINT ck_producto_segmento CHECK (segmento IN ('MICROCREDITO','CONSUMO')),
  subsegmento           VARCHAR2(60)  NOT NULL,
  nombre                VARCHAR2(80)  NOT NULL,
  rango_ventas          VARCHAR2(120),
  monto_minimo          NUMBER(12,2)  NOT NULL,
  monto_maximo          NUMBER(12,2)  NOT NULL,
  plazo_maximo_meses    NUMBER(3)     NOT NULL,
  tasa_sin_ahorro       NUMBER(5,2),
  tasa_con_ahorro       NUMBER(5,2),
  porcentaje_ahorro     NUMBER(5,2),
  tasa_ahorro           NUMBER(5,2),
  porcentaje_aportacion NUMBER(5,2),
  tasa_con_aportacion   NUMBER(5,2),
  tasa_referencial      NUMBER(5,2)   GENERATED ALWAYS AS (COALESCE(tasa_sin_ahorro, tasa_con_ahorro)) VIRTUAL,
  requiere_ahorro       CHAR(1)       DEFAULT 'N' NOT NULL CONSTRAINT ck_producto_ahorro CHECK (requiere_ahorro IN ('S','N')),
  descripcion           VARCHAR2(300),
  activo                CHAR(1)       DEFAULT 'S' NOT NULL CONSTRAINT ck_producto_activo CHECK (activo IN ('S','N')),
  CONSTRAINT ck_producto_montos CHECK (monto_maximo >= monto_minimo),
  CONSTRAINT ck_producto_tasa   CHECK (tasa_sin_ahorro IS NOT NULL OR tasa_con_ahorro IS NOT NULL)
);

