-- Sección 9: Estado de situación patrimonial / ingresos y gastos mensuales
CREATE TABLE tb_situacion_financiera (
  id_solicitud          NUMBER(10)    CONSTRAINT pk_situacion PRIMARY KEY CONSTRAINT fk_situacion_solicitud REFERENCES tb_solicitud_credito ON DELETE CASCADE,
  -- Activos
  efectivo              NUMBER(12,2)  DEFAULT 0 NOT NULL,
  bancos                NUMBER(12,2)  DEFAULT 0 NOT NULL,
  mobiliario            NUMBER(12,2)  DEFAULT 0 NOT NULL,
  vehiculos             NUMBER(12,2)  DEFAULT 0 NOT NULL,
  bienes_inmuebles      NUMBER(12,2)  DEFAULT 0 NOT NULL,
  cuentas_por_cobrar    NUMBER(12,2)  DEFAULT 0 NOT NULL,
  otros_activos         NUMBER(12,2)  DEFAULT 0 NOT NULL,
  -- Pasivos
  cuentas_por_pagar     NUMBER(12,2)  DEFAULT 0 NOT NULL,
  deudas_sfn_microcredito NUMBER(12,2) DEFAULT 0 NOT NULL,
  deudas_sfn_consumo    NUMBER(12,2)  DEFAULT 0 NOT NULL,
  deudas_sfn_comercial  NUMBER(12,2)  DEFAULT 0 NOT NULL,
  deudas_sfn_vivienda   NUMBER(12,2)  DEFAULT 0 NOT NULL,
  deudas_sector_comercial NUMBER(12,2) DEFAULT 0 NOT NULL,
  otros_pasivos         NUMBER(12,2)  DEFAULT 0 NOT NULL,
  -- Ingresos mensuales
  sueldo                NUMBER(12,2)  DEFAULT 0 NOT NULL,
  sueldo_conyuge        NUMBER(12,2)  DEFAULT 0 NOT NULL,
  arriendos             NUMBER(12,2)  DEFAULT 0 NOT NULL,
  pension_jubilacion    NUMBER(12,2)  DEFAULT 0 NOT NULL,
  comisiones            NUMBER(12,2)  DEFAULT 0 NOT NULL,
  remesas_intereses     NUMBER(12,2)  DEFAULT 0 NOT NULL,
  ingreso_ventas        NUMBER(12,2)  DEFAULT 0 NOT NULL,
  ingreso_ventas_conyuge NUMBER(12,2) DEFAULT 0 NOT NULL,
  otros_ingresos        NUMBER(12,2)  DEFAULT 0 NOT NULL,
  -- Egresos mensuales
  alimentacion          NUMBER(12,2)  DEFAULT 0 NOT NULL,
  arriendo              NUMBER(12,2)  DEFAULT 0 NOT NULL,
  servicios_basicos     NUMBER(12,2)  DEFAULT 0 NOT NULL,
  gastos_financieros    NUMBER(12,2)  DEFAULT 0 NOT NULL,
  transporte            NUMBER(12,2)  DEFAULT 0 NOT NULL,
  educacion             NUMBER(12,2)  DEFAULT 0 NOT NULL,
  salud                 NUMBER(12,2)  DEFAULT 0 NOT NULL,
  vestimenta            NUMBER(12,2)  DEFAULT 0 NOT NULL,
  otros_egresos         NUMBER(12,2)  DEFAULT 0 NOT NULL,
  -- Totales (columnas virtuales)
  total_activos  NUMBER(14,2) GENERATED ALWAYS AS (efectivo + bancos + mobiliario + vehiculos + bienes_inmuebles + cuentas_por_cobrar + otros_activos) VIRTUAL,
  total_pasivos  NUMBER(14,2) GENERATED ALWAYS AS (cuentas_por_pagar + deudas_sfn_microcredito + deudas_sfn_consumo + deudas_sfn_comercial + deudas_sfn_vivienda + deudas_sector_comercial + otros_pasivos) VIRTUAL,
  patrimonio     NUMBER(14,2) GENERATED ALWAYS AS ((efectivo + bancos + mobiliario + vehiculos + bienes_inmuebles + cuentas_por_cobrar + otros_activos)
                                                 - (cuentas_por_pagar + deudas_sfn_microcredito + deudas_sfn_consumo + deudas_sfn_comercial + deudas_sfn_vivienda + deudas_sector_comercial + otros_pasivos)) VIRTUAL,
  total_ingresos NUMBER(14,2) GENERATED ALWAYS AS (sueldo + sueldo_conyuge + arriendos + pension_jubilacion + comisiones + remesas_intereses + ingreso_ventas + ingreso_ventas_conyuge + otros_ingresos) VIRTUAL,
  total_egresos  NUMBER(14,2) GENERATED ALWAYS AS (alimentacion + arriendo + servicios_basicos + gastos_financieros + transporte + educacion + salud + vestimenta + otros_egresos) VIRTUAL,
  disponible     NUMBER(14,2) GENERATED ALWAYS AS ((sueldo + sueldo_conyuge + arriendos + pension_jubilacion + comisiones + remesas_intereses + ingreso_ventas + ingreso_ventas_conyuge + otros_ingresos)
                                                 - (alimentacion + arriendo + servicios_basicos + gastos_financieros + transporte + educacion + salud + vestimenta + otros_egresos)) VIRTUAL
);

